import esbuild from "esbuild";
import process from "process";
import path from "node:path";
import { readFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: src/ - see docs/ARCHITECTURE.md for the layer map.
*/
async function decodeBundledJson(encoded) {
	const binary = atob(encoded);
	const compressed = new Uint8Array(binary.length);
	for (let index = 0; index < binary.length; index++) compressed[index] = binary.charCodeAt(index);
	const stream = new Blob([compressed]).stream().pipeThrough(new DecompressionStream("gzip"));
	return JSON.parse(await new Response(stream).text());
}`;

const prod = process.argv[2] === "production";

const compressedQuranData = {
	name: "compressed-quran-data",
	setup(build) {
		build.onLoad({ filter: /\.json$/ }, async (args) => {
			if (!["ayahs-canonical.json", "quran-root-index.json"].includes(path.basename(args.path))) return;
			const compressed = gzipSync(await readFile(args.path)).toString("base64");
			return { contents: `export default decodeBundledJson("${compressed}");`, loader: "js" };
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	loader: { ".json": "json" },
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [compressedQuranData],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
